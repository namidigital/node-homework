// validation/userSchema.js
// Joi describes what a VALID registration body looks like.
// Analogy: an incoming-material inspection checklist. Anything that doesn't
// meet spec gets rejected at the receiving dock, before it enters the plant.

const Joi = require("joi");

const userSchema = Joi.object({
  email: Joi.string().trim().lowercase().email().required(),
  name: Joi.string().trim().min(3).max(30).required(),
  password: Joi.string()
    .trim()
    .min(8)
    // must include lowercase, uppercase, a number, and a special character
    .pattern(/^(?=.*[a-z])(?=.*[A-Z])(?=.*\d)(?=.*[^a-zA-Z0-9]).+$/)
    .required()
    .messages({
      "string.pattern.base":
        "Password must be at least 8 characters long and include upper and lower case letters, a number, and a special character.",
    }),
});

module.exports = { userSchema };
